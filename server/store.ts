function ensureDataDir() {
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
}

export function readLabState(): LabStatePayload {
  ensureDataDir();
  if (!fs.existsSync(DATA_FILE)) {
    fs.writeFileSync(DATA_FILE, JSON.stringify(INITIAL_SEED_STATE, null, 2), 'utf-8');
    return structuredClone(INITIAL_SEED_STATE);
  }
  try {
    const raw = fs.readFileSync(DATA_FILE, 'utf-8');
    return JSON.parse(raw) as LabStatePayload;
  } catch {
    fs.writeFileSync(DATA_FILE, JSON.stringify(INITIAL_SEED_STATE, null, 2), 'utf-8');
    return structuredClone(INITIAL_SEED_STATE);
  }
}

export function writeLabState(nextState: LabStatePayload): LabStatePayload {
  ensureDataDir();
  fs.writeFileSync(DATA_FILE, JSON.stringify(nextState, null, 2), 'utf-8');
  return nextState;
}
